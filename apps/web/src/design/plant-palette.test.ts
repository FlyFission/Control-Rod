import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

// Vitest runs from apps/web; paths are built as strings so the bundler leaves them alone.
const raw = readFileSync(resolve(process.cwd(), "../../design/art/palette.json"));
const css = readFileSync(resolve(process.cwd(), "src/design/plant-palette.css"), "utf8");
const roles = (JSON.parse(raw.toString("utf8")) as { roles: Record<string, string> }).roles;

describe("plant palette tokens", () => {
  it("are generated from design/art/palette.json and not stale (run tools/gen_plant_palette.py)", () => {
    const expected = [
      "/*",
      " * GENERATED by tools/gen_plant_palette.py from design/art/palette.json. Do not edit by hand.",
      ` * Input digest (sha256): ${createHash("sha256").update(raw).digest("hex")}`,
      " */",
      ":root {",
      ...Object.entries(roles).map(([role, hex]) => `  --plant-${role}: ${hex};`),
      "}",
      "",
    ].join("\n");
    expect(css).toBe(expected);
  });

  it("defines every role the instruments use", () => {
    for (const role of ["ground", "surface", "linework", "needs-you", "trip", "core-glow", "screen"]) expect(roles[role]).toMatch(/^#[0-9a-f]{6}$/);
  });
});
