//! Every package state, action, actor kind and way of signing, decided by the kernel and kept as a
//! table in `transition-table.tsv`. The same table is run against the WebAssembly build the
//! control plane loads (`transition_table.test.mjs`), so the two cannot drift apart, and any
//! change to a decision shows up as a change to the table in review.
//!
//! The table is generated, never typed: `CONTROLROD_BLESS=1 cargo test -p controlrod-kernel --test
//! transition_table` rewrites it from the kernel. The floors below are checked against every row
//! either way, so a rewritten table that breaks one still fails.

use controlrod_kernel::ReasonCode;
use controlrod_kernel::transition::{
    Action, ActorKind, PreCheckOutcome, Request, RuntimeIdentity, Status, decide,
};
use std::fmt::Write as _;
use std::path::Path;

const STATUSES: [Status; 6] = [
    Status::Draft,
    Status::Released,
    Status::InWork,
    Status::InVerification,
    Status::Accepted,
    Status::Closed,
];
const ACTIONS: [Action; 10] = [
    Action::Release,
    Action::Claim,
    Action::SubmitOutput,
    Action::SubmitPreCheck,
    Action::Revise,
    Action::Accept,
    Action::AcceptWithFindings,
    Action::Return,
    Action::Reject,
    Action::OverrideIndependence,
];
const ACTORS: [ActorKind; 3] = [ActorKind::Human, ActorKind::Agent, ActorKind::System];
/// How the request is signed: not at all, by a passkey over the digest on record, or by the
/// owner's signing policy.
const SIGNATURES: [&str; 3] = ["none", "passkey", "policy"];

const HEADER: &str = "\
# Generated by kernel/tests/transition_table.rs. Do not edit by hand; to rewrite it, run:
#   CONTROLROD_BLESS=1 cargo test -p controlrod-kernel --test transition_table
# Every other fact in each request is favourable: actor id \"actor-1\", author baseline
# \"author-1\", checker baseline \"checker-1\", author runtime claude/default, checker runtime
# codex/default, no owner override, pre-check pass, a written reason given, no preparation.
# signature none: no assertion and no policy. passkey: a verified assertion over the matching
# digest. policy: the owner's signing policy covers the step, with no assertion.
status\taction\tactor\tsignature\tallowed\treason\tnext
";

fn kebab<T: serde::Serialize>(value: T) -> String {
    serde_json::to_value(value)
        .ok()
        .and_then(|v| v.as_str().map(str::to_owned))
        .unwrap_or_default()
}

/// The reason names the WebAssembly binding returns.
fn reason_name(reason: ReasonCode) -> &'static str {
    match reason {
        ReasonCode::Allowed => "allowed",
        ReasonCode::NotImplemented => "not-implemented",
        ReasonCode::PolicyError => "policy-error",
        ReasonCode::NotHuman => "not-human",
        ReasonCode::Unsigned => "unsigned",
        ReasonCode::WrongState => "wrong-state",
        ReasonCode::NotIndependent => "not-independent",
        ReasonCode::MissingPreCheck => "missing-pre-check",
        ReasonCode::ReasonRequired => "reason-required",
        _ => "forbidden",
    }
}

fn request(status: Status, action: Action, actor_kind: ActorKind, signature: &str) -> Request {
    let runtime = |provider: &str| RuntimeIdentity {
        provider: provider.into(),
        model: "default".into(),
    };
    Request {
        status,
        action,
        actor_kind,
        actor_id: "actor-1".into(),
        author_baseline: Some("author-1".into()),
        checker_baseline: Some("checker-1".into()),
        author_runtime: Some(runtime("claude")),
        checker_runtime: Some(runtime("codex")),
        owner_override_verified: false,
        pre_check: Some(PreCheckOutcome::Pass),
        assertion_verified: signature == "passkey",
        digest_matches: signature == "passkey",
        policy_signed: signature == "policy",
        reason_given: true,
        preparation: None,
    }
}

struct Row {
    status: Status,
    action: Action,
    actor: ActorKind,
    signature: &'static str,
    allowed: bool,
    reason: &'static str,
    next: Option<Status>,
}

fn rows() -> Vec<Row> {
    let mut out = Vec::new();
    for status in STATUSES {
        for action in ACTIONS {
            for actor in ACTORS {
                for signature in SIGNATURES {
                    let outcome = decide(&request(status, action, actor, signature));
                    out.push(Row {
                        status,
                        action,
                        actor,
                        signature,
                        allowed: outcome.decision.is_allowed(),
                        reason: reason_name(outcome.decision.reason()),
                        next: outcome.next,
                    });
                }
            }
        }
    }
    out
}

fn render(rows: &[Row]) -> String {
    let mut text = HEADER.to_owned();
    for r in rows {
        let _ = writeln!(
            text,
            "{}\t{}\t{}\t{}\t{}\t{}\t{}",
            kebab(r.status),
            kebab(r.action),
            kebab(r.actor),
            r.signature,
            if r.allowed { "yes" } else { "no" },
            r.reason,
            r.next.map_or_else(|| "-".to_owned(), kebab),
        );
    }
    text
}

const HUMAN_ONLY: [Action; 6] = [
    Action::Release,
    Action::Accept,
    Action::AcceptWithFindings,
    Action::Return,
    Action::Reject,
    Action::OverrideIndependence,
];

#[test]
fn every_state_action_actor_and_signature_matches_the_table() -> std::io::Result<()> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/transition-table.tsv");
    let fresh = render(&rows());
    if std::env::var_os("CONTROLROD_BLESS").is_some() {
        std::fs::write(&path, &fresh)?;
    }
    let committed = std::fs::read_to_string(&path)?;
    assert!(
        committed == fresh,
        "the kernel's decisions differ from kernel/tests/transition-table.tsv; if the change is \
         intended, rewrite the table with CONTROLROD_BLESS=1 and review its diff"
    );
    Ok(())
}

#[test]
fn the_table_covers_every_combination_once() {
    assert_eq!(
        rows().len(),
        STATUSES.len() * ACTIONS.len() * ACTORS.len() * SIGNATURES.len()
    );
}

#[test]
fn every_row_keeps_the_floors() {
    for r in rows() {
        let at = format!(
            "{} {} {} {}",
            kebab(r.status),
            kebab(r.action),
            kebab(r.actor),
            r.signature
        );
        assert_eq!(
            r.allowed,
            r.next.is_some(),
            "{at}: only an allowed step moves"
        );
        assert_eq!(r.allowed, r.reason == "allowed", "{at}: reason matches");
        if !r.allowed {
            continue;
        }
        assert!(
            !matches!(r.status, Status::Accepted | Status::Closed),
            "{at}: accepted and closed packages never move"
        );
        let human_only = HUMAN_ONLY.contains(&r.action);
        match r.actor {
            ActorKind::Agent => assert!(!human_only, "{at}: an agent takes no human action"),
            ActorKind::Human => {
                assert!(human_only, "{at}: a person never poses as an agent");
                assert_ne!(r.signature, "none", "{at}: a person's action is signed");
                if r.action == Action::OverrideIndependence {
                    assert_eq!(
                        r.signature, "passkey",
                        "{at}: the override is always signed"
                    );
                }
            }
            ActorKind::System => {
                assert_eq!(
                    r.signature, "policy",
                    "{at}: the system acts only under the policy"
                );
                assert!(
                    matches!(r.action, Action::Release | Action::Accept),
                    "{at}: the system only releases and accepts"
                );
            }
        }
    }
}
