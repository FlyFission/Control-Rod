#!/usr/bin/env node
// Generates packs/nuclear-grade/ from a checkout of Nuclear-grade Context
// Engineering (NGCE, MIT), and checks the generated pack for hand edits.
//
//   node scripts/generate-nuclear-pack.mjs [--from <ngce checkout>] [--out <dir>]
//   node scripts/generate-nuclear-pack.mjs --check [--out <dir>]
//
// Generate reads only local files (no network). Membership comes from NGCE's
// CORE.md: the Core 7 tables and the decision-matrix rows named in CLUSTERS.
// Each card is compiled the same way for every skill: a fixed file header, then
// per skill its name, its frontmatter `description`, and its `## Decision
// contract` section, unchanged. A skill without that section stops the run.
// Reference copies, templates and LICENSE are byte-for-byte copies.
//
// Check needs no NGCE checkout. It fails when the files under the pack differ
// from the manifest's digests, when a file is added or missing, or when a card
// or token count no longer matches what the reference copies compile to.

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { countTokens } from "./lib/token-count.mjs";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const UPSTREAM = "https://github.com/FlyFission/nuclear-grade-context-engineering";
const DEFAULT_FROM = "/home/claude/ngce";
const DEFAULT_OUT = join(REPO, "packs", "nuclear-grade");
// Retained license evidence for docs/third-party/register.md.
const DEFAULT_LICENSES = join(REPO, "third_party", "licenses", "FlyFission__nuclear-grade-context-engineering");
const TEMPLATE_MODES = ["quick", "standard", "cm"];

// Decision-matrix row label in CORE.md -> cluster id.
const CLUSTERS = {
  "Agent authority": "agent-authority",
  "Configuration management": "configuration-management",
  "Claims discipline": "claims-discipline",
  "Incident & deficiency": "incident-deficiency",
  Hygiene: "hygiene",
  "Review panel": "review-panel",
};

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const lf = (text) => text.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
const posix = (path) => path.split(sep).join("/");

function fail(message) {
  throw new Error(`generate-nuclear-pack: ${message}`);
}

function section(text, heading) {
  const lines = lf(text).split("\n");
  const start = lines.findIndex((line) => line.trim() === heading);
  if (start < 0) return null;
  const level = heading.match(/^#+/)[0].length;
  const stop = new RegExp(`^#{1,${level}} `);
  let end = lines.findIndex((line, i) => i > start && stop.test(line));
  if (end < 0) end = lines.length;
  return lines.slice(start + 1, end).join("\n").replace(/^\n+|\s+$/g, "");
}

// Same rule as NGCE's split_frontmatter: the first `description:` line of the
// frontmatter, trimmed, with surrounding double quotes removed.
function description(text, name) {
  const body = lf(text);
  if (!body.startsWith("---\n")) fail(`${name}: no frontmatter`);
  const end = body.indexOf("\n---", 4);
  if (end < 0) fail(`${name}: unterminated frontmatter`);
  const line = body.slice(4, end).split("\n").find((l) => l.startsWith("description:"));
  const value = line ? line.slice("description:".length).trim().replace(/^"+|"+$/g, "") : "";
  if (!value || value === ">" || value === "|" || value === ">-" || value === "|-") {
    fail(`${name}: description must be a one-line frontmatter value`);
  }
  return value;
}

export function compileCard(title, commit, skills) {
  const header = [
    `# ${title}`,
    "",
    `<!-- Generated by scripts/generate-nuclear-pack.mjs from ${UPSTREAM} at ${commit}. Do not edit: regenerate. -->`,
  ].join("\n");
  const blocks = skills.map(({ name, text }) => {
    const contract = section(text, "## Decision contract");
    if (contract === null || contract === "") fail(`${name}: no "## Decision contract" section`);
    return [`## ${name}`, "", description(text, name), "", "### Decision contract", "", contract].join("\n");
  });
  return `${[header, ...blocks].join("\n\n")}\n`;
}

const cardTitle = (id) => (id === "core" ? "Nuclear-grade Core 7" : `Nuclear-grade cluster: ${id}`);

function parseCore(coreMd) {
  const core7 = section(coreMd, "## The Core 7");
  if (core7 === null) fail("CORE.md has no '## The Core 7' section");
  const core = [...core7.matchAll(/^\| \d+ \| \[`([a-z0-9-]+)`\]/gm)].map((m) => m[1]);
  if (core.length !== 7) fail(`CORE.md lists ${core.length} Core skills, expected 7`);

  const matrix = section(coreMd, "## The decision matrix");
  if (matrix === null) fail("CORE.md has no '## The decision matrix' section");
  const clusters = {};
  for (const row of matrix.split("\n").filter((line) => line.startsWith("| "))) {
    const cells = row.split(" | ");
    if (cells.length < 3) continue;
    const label = cells[1].match(/^\*\*(.+?)\*\*/)?.[1];
    const id = label && CLUSTERS[label];
    if (!id) continue;
    // Skills joined with "— plus ... only when" are conditional add-ons from
    // another cluster; only the unconditional list is the cluster's membership.
    const listed = cells.slice(2).join(" | ").split(" — plus ")[0];
    const skills = [...listed.matchAll(/\[`([a-z0-9-]+)`\]\(skills\/\1\/SKILL\.md\)/g)].map((m) => m[1]);
    if (skills.length === 0) fail(`cluster ${id} lists no skills`);
    clusters[id] = skills;
  }
  for (const id of Object.values(CLUSTERS)) if (!clusters[id]) fail(`CORE.md has no matrix row for ${id}`);
  return { core, clusters };
}

function parseTemplates(yaml) {
  const out = {};
  let inBlock = false;
  let mode = null;
  for (const line of lf(yaml).split("\n")) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    if (!/^\s/.test(line)) {
      inBlock = line.trim() === "templates:";
      mode = null;
      continue;
    }
    if (!inBlock) continue;
    const key = line.match(/^ {2}([a-z-]+):\s*$/);
    if (key) {
      mode = key[1];
      out[mode] = [];
      continue;
    }
    const item = line.match(/^ {4}- (\S+)\s*$/);
    if (item && mode) out[mode].push(item[1]);
  }
  for (const m of TEMPLATE_MODES) if (!out[m]?.length) fail(`nuclear-grade.yaml lists no ${m} templates`);
  return out;
}

export function resolveCommit(from) {
  const gitDir = join(from, ".git");
  if (existsSync(join(gitDir, "HEAD"))) {
    let head = readFileSync(join(gitDir, "HEAD"), "utf8").trim();
    if (/^[0-9a-f]{40}$/.test(head)) return head;
    const ref = head.replace(/^ref: /, "");
    if (existsSync(join(gitDir, ref))) return readFileSync(join(gitDir, ref), "utf8").trim();
    const packed = join(gitDir, "packed-refs");
    if (existsSync(packed)) {
      const hit = readFileSync(packed, "utf8").split("\n").find((l) => l.endsWith(` ${ref}`));
      if (hit) return hit.split(" ")[0];
    }
  }
  return execFileSync("git", ["-C", from, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
}

function listFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const entry of readdirSync(d, { withFileTypes: true })) {
      const path = join(d, entry.name);
      if (entry.isDirectory()) walk(path);
      else out.push(posix(relative(dir, path)));
    }
  };
  walk(dir);
  return out.sort();
}

export function generate({ from = DEFAULT_FROM, out = DEFAULT_OUT, licenses } = {}) {
  if (licenses === undefined && resolve(out) === DEFAULT_OUT) licenses = DEFAULT_LICENSES;
  from = resolve(from);
  if (!existsSync(join(from, "CORE.md"))) fail(`${from} is not an NGCE checkout (no CORE.md)`);
  const commit = resolveCommit(from);
  if (!/^[0-9a-f]{40}$/.test(commit)) fail(`could not read the commit of ${from}`);
  const { core, clusters } = parseCore(readFileSync(join(from, "CORE.md"), "utf8"));
  const templates = parseTemplates(readFileSync(join(from, "nuclear-grade.yaml"), "utf8"));

  const files = new Map();
  const sources = new Map(); // pack path -> upstream path it came from
  const skillBytes = new Map();
  for (const name of [...core, ...Object.values(clusters).flat()]) {
    if (skillBytes.has(name)) continue;
    const bytes = readFileSync(join(from, "skills", name, "SKILL.md"));
    skillBytes.set(name, bytes);
    files.set(`reference/${name}/SKILL.md`, bytes);
    sources.set(`reference/${name}/SKILL.md`, `skills/${name}/SKILL.md`);
  }
  const skills = (names) => names.map((name) => ({ name, text: skillBytes.get(name).toString("utf8") }));

  const manifest = {
    upstream: UPSTREAM,
    commit,
    license: "MIT",
    core: { card: "core.md", skills: core, tokens: 0 },
    clusters: {},
    templates: {},
    files: {},
  };
  const coreCard = compileCard(cardTitle("core"), commit, skills(core));
  files.set("core.md", Buffer.from(coreCard));
  sources.set("core.md", "compiled from CORE.md and the skills it lists");
  manifest.core.tokens = countTokens(coreCard);
  for (const id of Object.values(CLUSTERS)) {
    const card = compileCard(cardTitle(id), commit, skills(clusters[id]));
    files.set(`clusters/${id}.md`, Buffer.from(card));
    sources.set(`clusters/${id}.md`, "compiled from CORE.md and the skills it lists");
    manifest.clusters[id] = { card: `clusters/${id}.md`, skills: clusters[id], tokens: countTokens(card) };
  }
  for (const mode of TEMPLATE_MODES) {
    manifest.templates[mode] = templates[mode];
    for (const file of templates[mode]) {
      files.set(`templates/${mode}/${file}`, readFileSync(join(from, "templates", mode, file)));
      sources.set(`templates/${mode}/${file}`, `templates/${mode}/${file}`);
    }
  }
  files.set("LICENSE", readFileSync(join(from, "LICENSE")));
  sources.set("LICENSE", "LICENSE");

  rmSync(out, { recursive: true, force: true });
  for (const [path, bytes] of [...files].sort(([a], [b]) => (a < b ? -1 : 1))) {
    mkdirSync(dirname(join(out, path)), { recursive: true });
    writeFileSync(join(out, path), bytes);
    manifest.files[path] = `sha256:${sha256(bytes)}`;
  }
  writeFileSync(join(out, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  if (licenses) writeLicenseEvidence(licenses, from, commit, out, manifest, sources);
  return manifest;
}

function writeLicenseEvidence(dir, from, commit, out, manifest, sources) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "LICENSE"), readFileSync(join(from, "LICENSE")));
  const local = posix(relative(REPO, out));
  const tokensPy = readFileSync(join(from, "nuclear_grade", "tokens.py"));
  const lines = [
    "Upstream: FlyFission/nuclear-grade-context-engineering",
    `Commit: ${commit}`,
    "License: MIT",
    "Generated by: scripts/generate-nuclear-pack.mjs",
    "",
    "Upstream path | Local path | sha256 of the local file",
    ...Object.entries(manifest.files).map(
      ([path, digest]) => `${sources.get(path)} | ${local}/${path} | ${digest.replace("sha256:", "")}`,
    ),
    "",
    "Ported code (count_tokens and its constants, not copied byte for byte):",
    `nuclear_grade/tokens.py | scripts/lib/token-count.mjs | upstream sha256 ${sha256(tokensPy)}`,
  ];
  writeFileSync(join(dir, "INVENTORY.txt"), `${lines.join("\n")}\n`);
}

export function check({ out = DEFAULT_OUT } = {}) {
  const problems = [];
  const manifestPath = join(out, "manifest.json");
  if (!existsSync(manifestPath)) return [`${posix(relative(REPO, manifestPath))} is missing`];
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const listed = Object.keys(manifest.files ?? {});
  const present = listFiles(out).filter((path) => path !== "manifest.json");
  for (const path of present) if (!listed.includes(path)) problems.push(`${path}: not in manifest`);
  for (const path of listed) {
    const full = join(out, path);
    if (!existsSync(full)) {
      problems.push(`${path}: missing`);
      continue;
    }
    const digest = `sha256:${sha256(readFileSync(full))}`;
    if (digest !== manifest.files[path]) problems.push(`${path}: digest ${digest} != manifest ${manifest.files[path]}`);
  }
  // Recompile every card from the reference copies, so an edit to a card and
  // its manifest digest together is still caught.
  const cards = [["core", manifest.core], ...Object.entries(manifest.clusters ?? {})];
  for (const [id, entry] of cards) {
    try {
      const skills = entry.skills.map((name) => ({
        name,
        text: readFileSync(join(out, "reference", name, "SKILL.md"), "utf8"),
      }));
      const expected = compileCard(cardTitle(id), manifest.commit, skills);
      const cardPath = join(out, entry.card);
      if (!existsSync(cardPath) || readFileSync(cardPath, "utf8") !== expected) {
        problems.push(`${entry.card}: does not match what its reference skills compile to`);
      }
      if (countTokens(expected) !== entry.tokens) {
        problems.push(`${entry.card}: manifest tokens ${entry.tokens} != ${countTokens(expected)}`);
      }
    } catch (error) {
      problems.push(`${entry.card}: ${error.message}`);
    }
  }
  return problems;
}

function main(argv) {
  const arg = (name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const out = arg("--out") ? resolve(arg("--out")) : DEFAULT_OUT;
  if (argv.includes("--check")) {
    const problems = check({ out });
    if (problems.length) {
      console.error(`nuclear-grade pack check failed (${problems.length}):`);
      for (const p of problems) console.error(`  ${p}`);
      console.error("Regenerate with: node scripts/generate-nuclear-pack.mjs --from <ngce checkout>");
      process.exit(1);
    }
    console.log(`nuclear-grade pack check passed: ${posix(relative(REPO, out)) || out}`);
    return;
  }
  const manifest = generate({ from: arg("--from") ?? DEFAULT_FROM, out });
  console.log(`wrote ${posix(relative(REPO, out))} from ${manifest.commit} (${Object.keys(manifest.files).length} files + manifest.json)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
