#!/usr/bin/env python3
"""Generate apps/web/src/design/plant-palette.css from design/art/palette.json (AGENTS.md rules 3 and 5).

Each role becomes a --plant-<role> custom property on :root. The header names the sha256 of the
input so a stale output is detectable. Run: python3 tools/gen_plant_palette.py
"""
import hashlib, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design/art/palette.json"
OUT = ROOT / "apps/web/src/design/plant-palette.css"


def render(raw: bytes) -> str:
    roles = json.loads(raw)["roles"]
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        "/*",
        " * GENERATED by tools/gen_plant_palette.py from design/art/palette.json. Do not edit by hand.",
        f" * Input digest (sha256): {digest}",
        " */",
        ":root {",
    ]
    lines += [f"  --plant-{role}: {hexv};" for role, hexv in roles.items()]
    lines += ["}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render(SRC.read_bytes()))
    print(f"wrote {OUT.relative_to(ROOT)}")
