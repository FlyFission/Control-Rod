"""Generate the command inventory (workbench plan task 1.4; specification 10.1, WB-02).

For every command in services/api/src/commands/catalog.ts, lists where it is executed (file and
enclosing function) and what reaches it: HTTP routes, timers, and the functions in between. The
API test command-boundary.test.ts checks that the catalog and the executed commands agree; this
inventory shows reviewers the paths, and --check fails when it is stale.

Run: python3 tools/generate_command_inventory.py          (writes docs/commands/inventory.md)
     python3 tools/generate_command_inventory.py --check  (fails if the file is stale)
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "services" / "api" / "src"
OUT = ROOT / "docs" / "commands" / "inventory.md"

ENTRY = re.compile(r'^\s*"([a-z][a-z-]*\.[a-z-]+)":\s*entry\("([a-z-]+)",\s*"([a-z]+)",\s*"([^"]+)"\)', re.M)
CALL = re.compile(r'\b(?:command|grantTx)\(\s*\w+(?:\.\w+)*\s*,\s*"([a-z][a-z-]*\.[a-z-]+)"')
FUNC = re.compile(r'^\s*(?:export\s+)?(?:async\s+)?function\s+(\w+)', re.M)
ROUTE = re.compile(r'app\.(get|post|put|delete)(?:<[^(]*?>)?\(\s*"([^"]+)"')


def sources() -> dict[str, str]:
    return {str(p.relative_to(SRC)): p.read_text(encoding="utf-8")
            for p in sorted(SRC.rglob("*.ts")) if not p.name.endswith(".d.ts")}


def enclosing(text: str, offset: int) -> str:
    name = "(module)"
    for m in FUNC.finditer(text):
        if m.start() > offset:
            break
        name = m.group(1)
    return name


def blocks(text: str) -> list[tuple[str, str, int, int]]:
    """Route handlers as (method, path, start, end) spans: each runs until the next route."""
    found = list(ROUTE.finditer(text))
    return [(m.group(1).upper(), m.group(2), m.start(), found[i + 1].start() if i + 1 < len(found) else len(text))
            for i, m in enumerate(found)]


def callers(files: dict[str, str], fn: str, depth: int = 0, seen: frozenset[str] = frozenset()) -> set[str]:
    """Routes and timers that reach `fn`, following plain function calls up to a few levels."""
    out: set[str] = set()
    if depth > 4 or fn in seen:
        return out
    pattern = re.compile(rf"\b{re.escape(fn)}\(")
    for path, text in files.items():
        for method, route, start, end in blocks(text):
            if pattern.search(text, start, end):
                out.add(f"`{method} {route}`")
        if path == "app.ts":
            if re.search(rf"setInterval\([^)]*\b{re.escape(fn)}\b|const\s+\w+\s*=\s*\(\)\s*=>\s*{re.escape(fn)}\(", text):
                out.add("timer (lease sweep)")
        for m in pattern.finditer(text):
            parent = enclosing(text, m.start())
            if parent not in ("(module)", fn) and not any(s <= m.start() < e for _, _, s, e in blocks(text)):
                out |= callers(files, parent, depth + 1, seen | {fn})
    return out


def build() -> str:
    files = sources()
    catalog = ENTRY.findall(files["commands/catalog.ts"])
    sites: dict[str, list[str]] = {}
    for path, text in files.items():
        for m in CALL.finditer(text):
            sites.setdefault(m.group(1), []).append(f"`{path}` {enclosing(text, m.start())}")
    lines = [
        "# Command inventory",
        "",
        "Generated by `tools/generate_command_inventory.py` from `services/api/src`; do not edit by hand.",
        "Every controlled write runs as one of these commands on the writer connection",
        "([specification 10.1](../superpowers/specs/2026-10-29-workbench-ontology-design.md)). The application's",
        "ordinary pool is the reader role, which cannot write; `services/api/test/command-boundary.test.ts`",
        "checks the static rules and that this catalog matches the commands executed.",
        "",
        "| Command | Principal | Signature | Specification 10.2 row | Executed in | Reached from |",
        "|---|---|---|---|---|---|",
    ]
    for name, principal, signature, spec in catalog:
        where = sites.get(name, [])
        reach: set[str] = set()
        for site in where:
            fn = site.split(" ", 1)[1]
            reach |= {"startup (after migrations)"} if fn == "openDb" else callers(files, fn)
        lines.append(f"| `{name}` | {principal} | {signature} | {spec} | {'<br>'.join(sorted(set(where))) or 'unused'} | "
                     f"{', '.join(sorted(reach)) or 'no production caller yet (declared seam)'} |")
    lines += [
        "",
        "## Migrations and startup",
        "",
        "Migrations change the schema and run as the connecting owner (the migrator). Data changes that",
        "complete a migration run afterwards as commands on the writer login: `migration.backfill-tenancy`",
        "gives existing records their ownership envelopes, Members and credential records. The writer cannot",
        "change `schema_migrations` or the lifecycle rule tables. The logins themselves are described in",
        "[database-roles.md](database-roles.md).",
        "",
        "## Reading this table",
        "",
        "\"Executed in\" is where the command runs in source. \"Reached from\" follows plain function calls up",
        "to HTTP routes and timers; it is a static trace, not observed execution. A command with no production",
        "caller is a declared seam: its implementation and tests exist, and nothing in the running app",
        "invokes it yet.",
        "",
        "## Required links",
        "",
        "[Execution ledger](../superpowers/execution/2026-10-29-workbench-buildout.md), [plan](../superpowers/plans/2026-10-29-workbench-buildout.md).",
        "",
        "## Exit criteria",
        "",
        "Every command in the catalog is executed somewhere, and every executed command is in the catalog.",
        "",
        "## Source-lineage note",
        "",
        "Generated from Control Rod source; command rows follow the workbench specification section 10.2.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    text = build()
    if p.parse_args().check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run tools/generate_command_inventory.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
